/** Колода «вперемешку»: по несколько карточек из каждой колоды. */
export const MIX_ID = 'mix';

export type PlayCard = { text: string; deckId: string };

export function buildOrder(deckId: string): PlayCard[] {
  if (deckId === MIX_ID) {
    return shuffle(DECKS.flatMap((d) => shuffle(d.cards).slice(0, 6).map((text) => ({ text, deckId: d.id }))));
  }
  const d = DECKS.find((x) => x.id === deckId);
  return d ? shuffle(d.cards).map((text) => ({ text, deckId: d.id })) : [];
}

/** Для «Это или то» — два варианта из строки «A или B». */
export function splitChoice(text: string): [string, string] | null {
  const parts = text.split(/\s+или\s+/i);
  const cap = (t: string) => t.charAt(0).toUpperCase() + t.slice(1);
  return parts.length === 2 ? [cap(parts[0]), cap(parts[1])] : null;
}

export function shuffle<T>(items: T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}
