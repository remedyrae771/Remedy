/** Случайный вопрос, по возможности не из недавних. */
export function pickQuestion(recent: number[]): number {
  const fresh = GAME_QUESTIONS.map((_, i) => i).filter((i) => !recent.includes(i));
  const pool = fresh.length ? fresh : GAME_QUESTIONS.map((_, i) => i);
  return pool[Math.floor(Math.random() * pool.length)];
}
